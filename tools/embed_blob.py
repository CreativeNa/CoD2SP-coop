"""embed_blob.py - turn files into a C header of byte arrays, so the launcher is one self-contained exe.

    python tools\\embed_blob.py launcher\\blobs.h g_dll=bridge\\cod2net5.dll g_iwd=path\\zz_coop.iwd
"""

import sys


def main():
    out = sys.argv[1]
    parts = []
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = open(path, "rb").read()
        rows = []
        for i in range(0, len(data), 24):
            rows.append("  " + ",".join(str(b) for b in data[i:i + 24]))
        parts.append(f"static const unsigned char {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"
                     f"static const unsigned long {name}_len = {len(data)}UL;\n")
        print(f"{name}: {len(data)} bytes from {path}")
    with open(out, "w", newline="\n") as f:
        f.write("/* generated by tools/embed_blob.py - do not edit */\n" + "\n".join(parts))


if __name__ == "__main__":
    main()
